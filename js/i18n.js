    window.DesignlyticsI18n = {
        lang: localStorage.getItem("designlytics_lang") || "et",

        apply: function() {
            const lang = this.lang;
            const t = TRANSLATIONS[lang];
            if (!t) return;
            document.documentElement.lang = lang === "et" ? "et" : "en";

            document.querySelectorAll("[data-i18n]").forEach(function(el) {
                const key = el.getAttribute("data-i18n");
                const value = t[key];
                if (value === undefined) return;
                if (value.indexOf("<") !== -1) el.innerHTML = value;
                else el.textContent = value;
            });

            document.querySelectorAll("[data-i18n-placeholder]").forEach(function(el) {
                const key = el.getAttribute("data-i18n-placeholder");
                const value = t[key];
                if (value !== undefined) el.placeholder = value;
            });

            document.querySelectorAll(".lang-switcher [data-lang]").forEach(function(btn) {
                btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
                btn.setAttribute("aria-pressed", btn.getAttribute("data-lang") === lang ? "true" : "false");
            });
        },

        setLang: function(lang) {
            if (!TRANSLATIONS[lang]) return;
            this.lang = lang;
            localStorage.setItem("designlytics_lang", lang);
            this.apply();
        },

        get: function(key) {
            var t = TRANSLATIONS[this.lang];
            return t && t[key];
        }
    };

    document.addEventListener("DOMContentLoaded", function() {
        window.DesignlyticsI18n.apply();
        document.querySelectorAll(".lang-switcher [data-lang]").forEach(function(btn) {
            btn.addEventListener("click", function() {
                window.DesignlyticsI18n.setLang(this.getAttribute("data-lang"));
            });
        });
    });
